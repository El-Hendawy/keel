<?php

declare(strict_types=1);

namespace Keel\Orm\Dialect;

/**
 * Standard SQL:2008. Works on any database that follows it (DB2, Firebird 3+, H2, and
 * others behind PDO_ODBC); engine-specific dialects override what differs.
 */
class AnsiDialect implements Dialect
{
    public function name(): string
    {
        return 'ansi';
    }

    public function quote(string $identifier): string
    {
        return '"' . str_replace('"', '""', $identifier) . '"';
    }

    public function paginate(string $sql, ?int $limit, ?int $offset): string
    {
        if ($offset !== null && $offset > 0) {
            $sql .= ' OFFSET ' . $offset . ' ROWS';
        }

        return $limit === null ? $sql : $sql . ' FETCH ' . ($offset ? 'NEXT' : 'FIRST') . ' ' . $limit . ' ROWS ONLY';
    }

    public function bool(bool $value): bool|int
    {
        return $value ? 1 : 0;
    }

    public function upsert(string $table, array $columns, int $rows, array $conflict, array $update): string
    {
        // MERGE (SQL:2003) one row at a time; engines with native upserts override this.
        $q = $this->quote(...);
        $source = implode(', ', array_map(static fn (string $c): string => '? AS ' . $q($c), $columns));
        $on = implode(' AND ', array_map(static fn (string $c): string => 't.' . $q($c) . ' = s.' . $q($c), $conflict));
        $set = implode(', ', array_map(static fn (string $c): string => $q($c) . ' = s.' . $q($c), $update));

        return 'MERGE INTO ' . $q($table) . ' t USING (SELECT ' . $source . $this->dual() . ') s ON (' . $on . ')'
            . ($set === '' ? '' : ' WHEN MATCHED THEN UPDATE SET ' . $set)
            . ' WHEN NOT MATCHED THEN INSERT (' . implode(', ', array_map($q, $columns)) . ') VALUES (' . implode(', ', array_map(static fn (string $c): string => 's.' . $q($c), $columns)) . ')';
    }

    public function generatedKeys(): string
    {
        return 'last_insert_id';
    }

    public function columnType(array $column): string
    {
        return match ($column['type']) {
            'string' => 'VARCHAR(' . ($column['length'] ?? 255) . ')',
            'text' => 'CLOB',
            'int' => 'BIGINT',
            'float' => 'DOUBLE PRECISION',
            'decimal' => 'DECIMAL(' . ($column['precision'] ?? 18) . ', ' . ($column['scale'] ?? 4) . ')',
            'bool' => 'SMALLINT',
            'datetime' => 'TIMESTAMP',
            'json' => 'CLOB',
            'enum' => ($column['enum_int'] ?? false) ? 'BIGINT' : 'VARCHAR(64)',
            default => throw new \InvalidArgumentException("Unknown column type {$column['type']}."),
        };
    }

    public function autoIncrement(string $column): string
    {
        return $this->quote($column) . ' BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    }

    public function forUpdate(): string
    {
        return ' FOR UPDATE';
    }

    public function columnsQuery(): string
    {
        return 'SELECT column_name AS name FROM information_schema.columns WHERE table_name = ?';
    }

    public function tablesQuery(): string
    {
        return "SELECT table_name AS name FROM information_schema.tables WHERE table_schema NOT IN ('information_schema', 'pg_catalog')";
    }

    /** @return positive-int */
    public function maxInList(): int
    {
        return 900;
    }

    protected function dual(): string
    {
        return ' FROM (VALUES (0)) AS dual_row';
    }
}
