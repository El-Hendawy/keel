<?php

declare(strict_types=1);

namespace Keel\Orm\Dialect;

/** Oracle Database 12c+ (pdo_oci). Use uuid ids: auto-increment ids cannot be read back through PDO. */
final class OracleDialect extends AnsiDialect
{
    public function name(): string
    {
        return 'oci';
    }

    public function columnType(array $column): string
    {
        return match ($column['type']) {
            'string' => 'VARCHAR2(' . ($column['length'] ?? 255) . ' CHAR)',
            'int' => 'NUMBER(19)',
            'float' => 'BINARY_DOUBLE',
            'decimal' => 'NUMBER(' . ($column['precision'] ?? 18) . ', ' . ($column['scale'] ?? 4) . ')',
            'bool' => 'NUMBER(1)',
            'datetime' => 'TIMESTAMP(6)',
            'enum' => ($column['enum_int'] ?? false) ? 'NUMBER(19)' : 'VARCHAR2(64 CHAR)',
            default => parent::columnType($column),
        };
    }

    public function autoIncrement(string $column): string
    {
        return $this->quote($column) . ' NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    }

    public function generatedKeys(): string
    {
        return 'unsupported';
    }

    public function columnsQuery(): string
    {
        return 'SELECT column_name AS "name" FROM user_tab_columns WHERE table_name = ?';
    }

    public function tablesQuery(): string
    {
        return 'SELECT table_name AS "name" FROM user_tables';
    }

    protected function dual(): string
    {
        return ' FROM dual';
    }
}
