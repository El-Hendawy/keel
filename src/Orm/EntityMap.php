<?php

declare(strict_types=1);

namespace Keel\Orm;

use Keel\Container\Attribute\Singleton;
use Keel\Orm\Dialect\Dialect;
use Keel\Runtime\BuildManifest;

/**
 * The compiled entity metadata and generated mappers.
 *
 * @phpstan-type Column array{type: string, nullable: bool, column: string, readonly: bool, length?: int, precision?: int, scale?: int, enum?: class-string<\BackedEnum>, enum_int?: bool, unique?: bool, index?: bool}
 * @phpstan-type Relation array{kind: string, target: class-string, key: string, orderBy?: ?string, pivot?: string, local?: string, related?: string}
 * @phpstan-type Meta array{class: class-string, table: string, id: string, idColumn: string, idGenerated: string, tenant: ?string, version: ?string, createdAt: ?string, updatedAt: ?string, softDelete: ?string, columns: array<string, Column>, relations: array<string, Relation>, indexes: list<array{columns: list<string>, unique: bool}>, managed: list<string>, hydrator: string, extractor: string, setter: string}
 */
#[Singleton]
final readonly class EntityMap
{
    /** @var array<class-string, Meta> */
    private array $meta;

    private string $mappers;

    public function __construct(BuildManifest $manifest)
    {
        $class = $manifest->data['orm'] ?? null;
        $mappers = \is_string($class) && class_exists($class) ? $class : null;
        /** @var array<class-string, Meta> $meta generated by OrmCompiler */
        $meta = $mappers !== null && \defined($mappers . '::META') ? \constant($mappers . '::META') : [];
        $this->meta = $meta;
        $this->mappers = $mappers ?? '';
    }

    /**
     * @param class-string $class
     * @return Meta
     */
    public function meta(string $class): array
    {
        return $this->meta[$class] ?? throw new \InvalidArgumentException("$class is not an #[Entity] (or the build is stale: run `keel build`).");
    }

    /** @return array<class-string, Meta> */
    public function all(): array
    {
        return $this->meta;
    }

    /**
     * @template T of object
     * @param class-string<T> $class
     * @param array<string, mixed> $row
     * @return T
     */
    public function hydrate(string $class, array $row): object
    {
        $hydrate = [$this->mappers, $this->meta($class)['hydrator']];
        \assert(\is_callable($hydrate));
        $entity = $hydrate($row);
        \assert($entity instanceof $class);

        return $entity;
    }

    /** @return array<string, scalar|null> column => database value */
    public function extract(object $entity, Dialect $dialect): array
    {
        $extract = [$this->mappers, $this->meta($entity::class)['extractor']];
        \assert(\is_callable($extract));
        /** @var array<string, scalar|null> */
        return $extract($entity, $dialect);
    }

    public function set(object $entity, string $property, mixed $value): void
    {
        $set = [$this->mappers, $this->meta($entity::class)['setter']];
        \assert(\is_callable($set));
        $set($entity, $property, $value);
    }

    /**
     * The column definition of a property; unknown names fail with the list of valid ones.
     *
     * @param Meta $meta
     * @return Column
     */
    public static function column(array $meta, string $property): array
    {
        return $meta['columns'][$property] ?? throw new \InvalidArgumentException(
            "{$meta['class']} has no column property \"$property\". Columns: " . implode(', ', array_keys($meta['columns'])) . '.',
        );
    }

    /**
     * Converts a PHP value for a comparison against a column.
     *
     * @param Column $column
     */
    public static function toDb(array $column, mixed $value, Dialect $dialect): string|int|float|bool|null
    {
        return match (true) {
            $value === null => null,
            $value instanceof \BackedEnum => $value->value,
            $value instanceof \DateTimeInterface => Values::toDateTime($value),
            \is_bool($value) => $column['type'] === 'bool' ? $dialect->bool($value) : (int) $value,
            \is_array($value) => Values::toJson($value),
            \is_scalar($value) => $value,
            default => throw new \InvalidArgumentException('Cannot compare ' . $column['column'] . ' with ' . get_debug_type($value) . '.'),
        };
    }
}
