<?php

declare(strict_types=1);

namespace Keel\Console;

/**
 * `keel deploy:docker` and `keel deploy:kubernetes`: production container and cluster files
 * that match how Keel runs: `keel run` on port 8080, the build compiled into the image,
 * liveness and readiness probes on the health endpoints, a drain on SIGTERM, and no root.
 */
final readonly class DeploymentGenerator
{
    public function __construct(private string $root)
    {
    }

    /**
     * @param list<string> $extensions PHP extensions to install
     * @return list<string> files written
     */
    public function docker(array $extensions = ['pcntl', 'pdo_pgsql', 'pgsql', 'pdo_mysql', 'redis', 'opcache', 'sockets']): array
    {
        $installed = implode(' ', $extensions);
        $dockerfile = <<<DOCKER
            # syntax=docker/dockerfile:1
            # Generated by `keel deploy:docker`. Build: docker build -t app .
            FROM composer:2 AS vendor
            WORKDIR /app
            COPY composer.json composer.lock ./
            RUN composer install --no-dev --no-scripts --no-autoloader --no-interaction --prefer-dist
            COPY . .
            RUN composer dump-autoload --classmap-authoritative --no-dev

            FROM php:8.4-cli-bookworm
            COPY --from=mlocati/php-extension-installer:2 /usr/bin/install-php-extensions /usr/local/bin/
            RUN install-php-extensions $installed \\
             && printf 'opcache.enable_cli=1\\nopcache.validate_timestamps=0\\nmemory_limit=256M\\n' > /usr/local/etc/php/conf.d/keel.ini
            WORKDIR /app
            COPY --from=vendor /app /app
            # Compile routes, the container, hydrators and serializers into the image.
            RUN KEEL_ENV=prod vendor/bin/keel build --env=prod \\
             && mkdir -p var && chown -R www-data:www-data var
            ENV KEEL_ENV=prod
            USER www-data
            EXPOSE 8080
            STOPSIGNAL SIGTERM
            HEALTHCHECK --interval=10s --timeout=2s --start-period=10s CMD php -r 'exit(@file_get_contents("http://127.0.0.1:8080/health/live") === false ? 1 : 0);'
            # One process per CPU by default; each serves many requests concurrently.
            CMD ["vendor/bin/keel", "run", "--host=0.0.0.0", "--port=8080"]

            DOCKER;
        $ignore = ".git\n.github\nvendor\nvar\nnode_modules\ntests\n*.md\n.env\n.env.*\n.DS_Store\n._*\n";

        return $this->write(['Dockerfile' => $dockerfile, '.dockerignore' => $ignore]);
    }

    /** @return list<string> files written */
    public function kubernetes(string $name, string $image, int $replicas = 2, int $maxReplicas = 10): array
    {
        if (preg_match('/^[a-z]([-a-z0-9]{0,61}[a-z0-9])?$/', $name) !== 1) {
            throw new \InvalidArgumentException('--name must be a DNS label: lower case letters, digits and "-".');
        }
        $minAvailable = max(1, $replicas - 1);
        $yaml = <<<YAML
            # Generated by `keel deploy:kubernetes`. Secrets (APP_KEY, DATABASE_DSN, ...) come from the
            # Secret "$name-secrets": kubectl create secret generic $name-secrets --from-literal=APP_KEY=...
            apiVersion: apps/v1
            kind: Deployment
            metadata:
              name: $name
              labels: {app.kubernetes.io/name: $name}
            spec:
              replicas: $replicas
              revisionHistoryLimit: 5
              selector:
                matchLabels: {app.kubernetes.io/name: $name}
              strategy:
                type: RollingUpdate
                rollingUpdate: {maxUnavailable: 0, maxSurge: 1}
              template:
                metadata:
                  labels: {app.kubernetes.io/name: $name}
                  annotations:
                    prometheus.io/scrape: "true"
                    prometheus.io/port: "8080"
                    prometheus.io/path: /metrics
                spec:
                  terminationGracePeriodSeconds: 40
                  securityContext:
                    runAsNonRoot: true
                    seccompProfile: {type: RuntimeDefault}
                  containers:
                    - name: app
                      image: $image
                      ports: [{name: http, containerPort: 8080}]
                      env:
                        - {name: KEEL_ENV, value: prod}
                      envFrom:
                        - secretRef: {name: $name-secrets, optional: true}
                      resources:
                        requests: {cpu: 250m, memory: 256Mi}
                        limits: {memory: 512Mi}
                      securityContext:
                        allowPrivilegeEscalation: false
                        capabilities: {drop: [ALL]}
                      startupProbe:
                        httpGet: {path: /health/live, port: http}
                        periodSeconds: 2
                        failureThreshold: 30
                      livenessProbe:
                        httpGet: {path: /health/live, port: http}
                        periodSeconds: 10
                      readinessProbe:
                        httpGet: {path: /health/ready, port: http}
                        periodSeconds: 5
                        failureThreshold: 2
                      lifecycle:
                        # Let endpoints update before SIGTERM; `keel run` then drains in-flight requests.
                        preStop: {exec: {command: ["sleep", "5"]}}
            ---
            apiVersion: v1
            kind: Service
            metadata:
              name: $name
              labels: {app.kubernetes.io/name: $name}
            spec:
              selector: {app.kubernetes.io/name: $name}
              ports: [{name: http, port: 80, targetPort: http}]
            ---
            apiVersion: autoscaling/v2
            kind: HorizontalPodAutoscaler
            metadata:
              name: $name
            spec:
              scaleTargetRef: {apiVersion: apps/v1, kind: Deployment, name: $name}
              minReplicas: $replicas
              maxReplicas: $maxReplicas
              metrics:
                - type: Resource
                  resource: {name: cpu, target: {type: Utilization, averageUtilization: 70}}
            ---
            apiVersion: policy/v1
            kind: PodDisruptionBudget
            metadata:
              name: $name
            spec:
              minAvailable: $minAvailable
              selector:
                matchLabels: {app.kubernetes.io/name: $name}

            YAML;

        return $this->write(["deploy/kubernetes/$name.yaml" => $yaml]);
    }

    /**
     * @param array<string, string> $files
     * @return list<string>
     */
    private function write(array $files): array
    {
        foreach (array_keys($files) as $file) {
            if (file_exists($this->root . '/' . $file)) {
                throw new \RuntimeException("$file already exists; nothing was written. Delete it to regenerate.");
            }
        }
        foreach ($files as $file => $content) {
            $path = $this->root . '/' . $file;
            if (!is_dir(\dirname($path))) {
                mkdir(\dirname($path), 0o777, true);
            }
            file_put_contents($path, $content);
        }

        return array_keys($files);
    }
}
