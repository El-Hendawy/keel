<?php

declare(strict_types=1);

namespace Keel\Build\Fix;

use Keel\Build\Php;
use Keel\Fix\Attribute\Field;
use Keel\Fix\Attribute\FixMessage;
use Keel\Fix\Attribute\Group;
use Keel\Fix\FixContext;
use ReflectionClass;
use ReflectionNamedType;

/**
 * Compiles #[FixMessage] classes into a codec class (one decode and one encode method per
 * message and component) and checks #[FixHandler] signatures. Like the HTTP hydrators,
 * nothing about a message is discovered with reflection at runtime.
 */
final class FixCompiler
{
    /** @var list<string> */
    public array $errors = [];

    /** @var array<string, string> class => generated methods */
    private array $methods = [];

    /** @var array<string, array{class: class-string, decoder: string, encoder: string}> msgType => codec */
    private array $messages = [];

    /** @var array<string, class-string> msgType => handler class */
    private array $handlers = [];

    /** @param class-string $class */
    public function message(string $class): void
    {
        $reflection = new ReflectionClass($class);
        $type = ($reflection->getAttributes(FixMessage::class)[0] ?? null)?->newInstance()->type;
        if ($type === null) {
            return;
        }
        if (\in_array($type, ['0', '1', '2', '3', '4', '5', 'A'], true)) {
            $this->errors[] = "$class declares MsgType $type, which is a session message handled by Keel.";

            return;
        }
        if (isset($this->messages[$type])) {
            $this->errors[] = "MsgType $type is declared by both {$this->messages[$type]['class']} and $class.";

            return;
        }
        $id = self::id($class);
        $this->compile($class);
        $this->messages[$type] = ['class' => $class, 'decoder' => "d_$id", 'encoder' => "e_$id"];
    }

    /** @param class-string $class */
    public function handler(string $class): void
    {
        $invoke = method_exists($class, '__invoke') ? new \ReflectionMethod($class, '__invoke') : null;
        $params = $invoke?->getParameters() ?? [];
        $message = $params[0] ?? null;
        $type = $message?->getType();
        $context = ($params[1] ?? null)?->getType();
        $msgClass = $type instanceof ReflectionNamedType ? $type->getName() : '';
        $msgType = null;
        foreach ($this->messages as $t => $codec) {
            if ($codec['class'] === $msgClass) {
                $msgType = (string) $t;
            }
        }
        if ($invoke === null || $msgType === null || \count($params) > 2 || ($context !== null && (!$context instanceof ReflectionNamedType || $context->getName() !== FixContext::class))) {
            $this->errors[] = "FIX handler $class must define __invoke(SomeFixMessage \$message, FixContext \$fix) where SomeFixMessage has #[FixMessage].";

            return;
        }
        if (isset($this->handlers[$msgType])) {
            $this->errors[] = "MsgType $msgType has two FIX handlers: {$this->handlers[$msgType]} and $class.";

            return;
        }
        $this->handlers[$msgType] = $class;
    }

    /** @return array{messages: array<string, array{class: class-string, decoder: string, encoder: string}>, handlers: array<string, class-string>, classes: array<string, string>, codec: string} */
    public function manifest(string $codecClass): array
    {
        $classes = [];
        foreach ($this->messages as $type => $codec) {
            $classes[$codec['class']] = (string) $type; // numeric MsgTypes ("8") became int keys
        }

        return ['messages' => $this->messages, 'handlers' => $this->handlers, 'classes' => $classes, 'codec' => $codecClass];
    }

    public function isEmpty(): bool
    {
        return $this->messages === [];
    }

    public function compileClass(string $namespace, string $class): string
    {
        ksort($this->methods);

        return "<?php\n\n// Generated by Keel. Do not edit: run `keel build` instead.\n\ndeclare(strict_types=1);\n\nnamespace $namespace;\n\n"
            . "use Keel\\Fix\\Fields as F;\n\nfinal class $class\n{\n" . implode("\n", $this->methods) . "}\n";
    }

    /** @param class-string $class */
    private function compile(string $class): void
    {
        if (isset($this->methods[$class])) {
            return;
        }
        $this->methods[$class] = ''; // guards against recursion
        $reflection = new ReflectionClass($class);
        $constructor = $reflection->getConstructor();
        $id = self::id($class);
        $decode = [];
        $encode = [];
        $groups = [];
        $arguments = [];
        foreach ($constructor?->getParameters() ?? [] as $parameter) {
            $name = $parameter->getName();
            $where = "$class::\$$name";
            $type = $parameter->getType();
            $field = ($parameter->getAttributes(Field::class)[0] ?? null)?->newInstance();
            $group = ($parameter->getAttributes(Group::class)[0] ?? null)?->newInstance();
            if (!$type instanceof ReflectionNamedType || ($field === null && $group === null)) {
                $this->errors[] = "$where needs #[Field(tag)] or #[Group(count, of)] and a single type.";
                continue;
            }
            if (!$reflection->hasProperty($name) || !$reflection->getProperty($name)->isPublic()) {
                $this->errors[] = "$where must be a public promoted property.";
                continue;
            }
            $optional = $parameter->isDefaultValueAvailable();
            if ($group !== null) {
                if ($type->getName() !== 'array' || !class_exists($group->of)) {
                    $this->errors[] = "$where: #[Group] must be on an array of an existing component class.";
                    continue;
                }
                $this->compile($group->of);
                $members = $this->tagsOf($group->of);
                $component = self::id($group->of);
                $groups[] = "        \$g$name = F::extractGroup(\$pairs, {$group->count}, " . Php::export($members) . ");";
                $arguments[] = "            $name: array_map(self::d_$component(...), \$g$name),";
                $encode[] = "        if (\$o->$name !== []) {\n            \$out[] = [{$group->count}, (string) \\count(\$o->$name)];\n"
                    . "            foreach (\$o->$name as \$item) {\n                \\array_push(\$out, ...self::e_$component(\$item));\n            }\n        }";
                continue;
            }
            $tag = $field->tag;
            $typeName = $type->getName();
            $convert = match (true) {
                $typeName === 'string' => '$v',
                $typeName === 'int' => "F::int(\$v, $tag)",
                $typeName === 'float' => "F::float(\$v, $tag)",
                $typeName === 'bool' => "F::bool(\$v, $tag)",
                $typeName === \DateTimeImmutable::class => "F::time(\$v, $tag)",
                enum_exists($typeName) && is_subclass_of($typeName, \BackedEnum::class) => "\\$typeName::tryFrom(" . ((new \ReflectionEnum($typeName))->getBackingType()?->getName() === 'int' ? "F::int(\$v, $tag)" : '$v') . ") ?? throw F::invalid($tag)",
                default => null,
            };
            if ($convert === null) {
                $this->errors[] = "$where: FIX fields can be string, int, float, bool, DateTimeImmutable or a backed enum, not $typeName.";
                continue;
            }
            $default = $optional ? Php::export($parameter->getDefaultValue()) : 'null';
            $arguments[] = match (true) {
                !$optional && !$type->allowsNull() => "            $name: " . str_replace('$v', "F::required(\$f, $tag)", $convert) . ',',
                $convert === '$v' => "            $name: \$f[$tag] ?? $default,",
                default => "            $name: (\$v = \$f[$tag] ?? null) === null ? $default : $convert,",
            };
            $value = match (true) {
                $typeName === 'string' => "\$o->$name",
                $typeName === 'int' => "(string) \$o->$name",
                $typeName === 'float' => "F::decimal(\$o->$name)",
                $typeName === 'bool' => "(\$o->$name ? 'Y' : 'N')",
                $typeName === \DateTimeImmutable::class => "\\Keel\\Fix\\Time::timestamp(\$o->$name)",
                default => "(string) \$o->{$name}->value",
            };
            $encode[] = $type->allowsNull()
                ? "        if (\$o->$name !== null) {\n            \$out[] = [$tag, $value];\n        }"
                : "        \$out[] = [$tag, $value];";
        }

        $this->methods[$class] = "    /** @param list<array{0: int, 1: string}> \$pairs */\n"
            . "    public static function d_$id(array \$pairs): \\$class\n    {\n"
            . implode("\n", $groups) . ($groups === [] ? '' : "\n")
            . "        \$f = F::index(\$pairs);\n\n        return new \\$class(\n" . implode("\n", $arguments) . "\n        );\n    }\n\n"
            . "    /** @return list<array{0: int, 1: string}> */\n"
            . "    public static function e_$id(\\$class \$o): array\n    {\n        \$out = [];\n" . implode("\n", $encode) . "\n\n        return \$out;\n    }\n";
    }

    /**
     * @param class-string $class
     * @return list<int> the tags of a component, first one first (it delimits instances)
     */
    private function tagsOf(string $class): array
    {
        $tags = [];
        foreach ((new ReflectionClass($class))->getConstructor()?->getParameters() ?? [] as $parameter) {
            $field = ($parameter->getAttributes(Field::class)[0] ?? null)?->newInstance();
            $group = ($parameter->getAttributes(Group::class)[0] ?? null)?->newInstance();
            if ($field !== null) {
                $tags[] = $field->tag;
            } elseif ($group !== null) {
                $tags = [...$tags, $group->count, ...$this->tagsOf($group->of)];
            }
        }
        if ($tags === []) {
            $this->errors[] = "FIX component $class has no #[Field] parameters.";
        }

        return $tags;
    }

    private static function id(string $class): string
    {
        return strtolower(str_replace('\\', '_', $class));
    }
}
