<?php

declare(strict_types=1);

namespace Keel\Build\Sdk;

/**
 * Generates a dependency-free TypeScript client from the OpenAPI document the build
 * already produces: one interface per schema and one typed method per operation.
 * Errors are thrown as `ApiError` carrying the RFC 9457 problem document.
 *
 *     const api = createClient({ baseUrl: 'https://api.example.com', token: () => session.token });
 *     const order = await api.ordersCreate({ merchantId, items });
 */
final class TypeScriptGenerator
{
    /** @param array<string, mixed> $openApi */
    public function generate(array $openApi): string
    {
        $schemas = self::map(self::map($openApi['components'] ?? [])['schemas'] ?? []);
        $out = "// Generated by Keel from openapi.json. Do not edit: run `keel sdk` instead.\n/* eslint-disable */\n\n";
        foreach ($schemas as $name => $schema) {
            $out .= $this->declaration((string) $name, self::map($schema));
        }
        $out .= self::RUNTIME;

        $methods = [];
        foreach (self::map($openApi['paths'] ?? []) as $path => $operations) {
            foreach (self::map($operations) as $method => $operation) {
                $methods[] = $this->method((string) $path, strtoupper((string) $method), self::map($operation));
            }
        }
        $out .= "\nexport function createClient(options: ClientOptions) {\n  const call = caller(options);\n  return {\n" . implode('', $methods) . "  };\n}\n\nexport type Client = ReturnType<typeof createClient>;\n";

        return $out;
    }

    /** @param array<string, mixed> $schema */
    private function declaration(string $name, array $schema): string
    {
        $type = self::identifier($name);
        if (($schema['type'] ?? null) !== 'object') {
            return "export type $type = " . $this->type($schema) . ";\n\n";
        }

        return "export interface $type " . $this->type($schema) . "\n\n";
    }

    /** @param array<string, mixed> $operation */
    private function method(string $path, string $method, array $operation): string
    {
        $name = self::identifier(str_replace('.', ' ', self::str($operation['operationId'] ?? strtolower($method) . $path)), false);
        $args = [];
        $pathParams = [];
        $queryParams = [];
        foreach (self::list($operation['parameters'] ?? []) as $parameter) {
            $parameter = self::map($parameter);
            $param = self::str($parameter['name'] ?? '');
            $tsType = $this->type(self::map($parameter['schema'] ?? []));
            if (($parameter['in'] ?? '') === 'path') {
                $pathParams[] = $param;
                $args[] = self::identifier($param, false) . ": $tsType";
            } else {
                $queryParams[] = '    ' . self::property($param) . (($parameter['required'] ?? false) === true ? '' : '?') . ": $tsType;";
            }
        }
        $body = self::map(self::map(self::map($operation['requestBody'] ?? [])['content'] ?? [])['application/json'] ?? []);
        $hasBody = isset($body['schema']);
        if ($hasBody) {
            $args[] = 'body: ' . $this->type(self::map($body['schema'] ?? []));
        }
        if ($queryParams !== []) {
            $args[] = "query: {\n" . implode("\n", $queryParams) . "\n  } = {}";
        }
        $args[] = 'init: RequestInit = {}';

        $result = 'void';
        foreach (self::map($operation['responses'] ?? []) as $status => $response) {
            if ((int) $status >= 200 && (int) $status < 300) {
                $schema = self::map(self::map(self::map(self::map($response)['content'] ?? [])['application/json'] ?? [])['schema'] ?? []);
                $result = $schema === [] ? 'void' : $this->type($schema);
                break;
            }
        }
        $url = '`' . preg_replace_callback('/\{(\w+)\}/', static fn (array $m): string => '${encodeURIComponent(String(' . self::identifier($m[1], false) . '))}', $path) . '`';
        $summary = isset($operation['summary']) ? '    /** ' . str_replace('*/', '*\/', self::str($operation['summary'])) . " */\n" : '';

        return $summary . "    $name: (" . implode(', ', $args) . "): Promise<$result> =>\n"
            . "      call<$result>('$method', $url, " . ($queryParams !== [] ? 'query' : 'undefined') . ', ' . ($hasBody ? 'body' : 'undefined') . ", init),\n";
    }

    /** @param array<string, mixed> $schema */
    private function type(array $schema): string
    {
        if (isset($schema['$ref']) && \is_string($schema['$ref'])) {
            return self::identifier((string) substr($schema['$ref'], (int) strrpos($schema['$ref'], '/') + 1));
        }
        if (isset($schema['oneOf'])) {
            return implode(' | ', array_map(fn (mixed $s): string => $this->type(self::map($s)), self::list($schema['oneOf'])));
        }
        if (isset($schema['enum'])) {
            return implode(' | ', array_map(static fn (mixed $v): string => json_encode($v, \JSON_THROW_ON_ERROR), self::list($schema['enum'])));
        }
        $type = $schema['type'] ?? 'unknown';
        if (\is_array($type)) {
            return implode(' | ', array_map(fn (mixed $t): string => $this->type(['type' => $t] + $schema), $type));
        }

        return match ($type) {
            'string' => 'string',
            'integer', 'number' => 'number',
            'boolean' => 'boolean',
            'null' => 'null',
            'array' => 'Array<' . $this->type(self::map($schema['items'] ?? [])) . '>',
            'object' => $this->object($schema),
            default => 'unknown',
        };
    }

    /** @param array<string, mixed> $schema */
    private function object(array $schema): string
    {
        $required = self::list($schema['required'] ?? []);
        $lines = [];
        foreach (self::map($schema['properties'] ?? []) as $name => $property) {
            $property = self::map($property);
            $doc = isset($property['description']) ? '  /** ' . str_replace('*/', '*\/', self::str($property['description'])) . " */\n" : '';
            $lines[] = $doc . '  ' . self::property((string) $name) . (\in_array($name, $required, true) ? '' : '?') . ': ' . $this->type($property) . ';';
        }

        return $lines === [] ? 'Record<string, never>' : "{\n" . implode("\n", $lines) . "\n}";
    }

    private static function identifier(string $name, bool $type = true): string
    {
        $words = preg_split('/[^A-Za-z0-9]+/', $name, -1, \PREG_SPLIT_NO_EMPTY) ?: ['value'];
        $id = implode('', array_map(ucfirst(...), $words));
        $id = $type ? $id : lcfirst($id);

        return preg_match('/^\d/', $id) === 1 ? "_$id" : $id;
    }

    private static function property(string $name): string
    {
        return preg_match('/^[A-Za-z_$][\w$]*$/', $name) === 1 ? $name : json_encode($name, \JSON_THROW_ON_ERROR);
    }

    /** @return array<string, mixed> */
    private static function map(mixed $value): array
    {
        $map = [];
        foreach (\is_array($value) ? $value : [] as $key => $item) {
            $map[(string) $key] = $item;
        }

        return $map;
    }

    private static function str(mixed $value): string
    {
        return \is_scalar($value) ? (string) $value : '';
    }

    /** @return list<mixed> */
    private static function list(mixed $value): array
    {
        return \is_array($value) ? array_values($value) : [];
    }

    private const string RUNTIME = <<<'TS'
        export interface Problem {
          type: string;
          title: string;
          status: number;
          detail?: string;
          errors?: Array<{ path: string; code: string; message: string }>;
          requestId?: string;
          [key: string]: unknown;
        }

        export class ApiError extends Error {
          constructor(public readonly status: number, public readonly problem: Problem) {
            super(problem.detail ?? problem.title);
          }
        }

        export interface ClientOptions {
          baseUrl: string;
          /** A Keel token or JWT, or a function returning one per request. */
          token?: string | (() => string | undefined | Promise<string | undefined>);
          fetch?: typeof fetch;
          headers?: Record<string, string>;
        }

        function caller(options: ClientOptions) {
          const doFetch = options.fetch ?? fetch;
          return async function call<T>(method: string, path: string, query: Record<string, unknown> | undefined, body: unknown, init: RequestInit): Promise<T> {
            const url = new URL(options.baseUrl.replace(/\/$/, '') + path);
            for (const [key, value] of Object.entries(query ?? {})) {
              if (value !== undefined && value !== null) url.searchParams.set(key, String(value));
            }
            const headers: Record<string, string> = { Accept: 'application/json', ...options.headers };
            const token = typeof options.token === 'function' ? await options.token() : options.token;
            if (token) headers.Authorization = `Bearer ${token}`;
            if (body !== undefined) headers['Content-Type'] = 'application/json';
            const response = await doFetch(url, { ...init, method, headers: { ...headers, ...(init.headers as Record<string, string> | undefined) }, body: body === undefined ? undefined : JSON.stringify(body) });
            if (!response.ok) {
              const problem = (await response.json().catch(() => ({ type: 'about:blank', title: response.statusText, status: response.status }))) as Problem;
              throw new ApiError(response.status, problem);
            }
            return (response.status === 204 ? undefined : await response.json()) as T;
          };
        }

        TS;
}
