<?php

declare(strict_types=1);

namespace Keel\Build\Service;

use Keel\Build\Php;
use Keel\Container\Lifetime;

/**
 * Validates the service graph and generates the compiled container.
 *
 * Validation runs before any code is written:
 *  - every dependency resolves to a registered service, a binding or a default;
 *  - there are no cycles;
 *  - no Singleton depends, directly or through Transients, on a Scoped service.
 */
final class ContainerCompiler
{
    /** @var list<string> */
    public array $errors = [];

    /** @var array<string, list<string>> service id => resolved dependency ids */
    private array $edges = [];

    /** @var array<string, bool> */
    private array $needsScope = [];

    /**
     * @param array<string, ServiceDefinition> $services
     * @param array<string, string> $aliases abstract => concrete
     */
    public function __construct(private readonly array $services, private readonly array $aliases)
    {
    }

    public function validate(): bool
    {
        foreach ($this->aliases as $abstract => $concrete) {
            if (!isset($this->services[$concrete])) {
                $this->errors[] = "Binding $abstract => $concrete points to a class that is not a service. Add a lifetime attribute to $concrete.";
            }
        }

        foreach ($this->services as $id => $definition) {
            $this->edges[$id] = $this->dependenciesOf($definition);
        }

        $this->detectCycles();
        if ($this->errors !== []) {
            return false;
        }

        foreach ($this->services as $id => $definition) {
            if ($definition->lifetime !== Lifetime::Singleton) {
                continue;
            }
            foreach ($this->edges[$id] as $dependency) {
                if ($this->requiresScope($dependency)) {
                    $this->errors[] = \sprintf(
                        'Singleton %s cannot depend on %s. %s',
                        self::short($definition->origin ?: $id),
                        $this->describeScopePath($dependency),
                        'Make it Scoped, or depend on something with a longer lifetime.',
                    );
                }
            }
        }

        return $this->errors === [];
    }

    /** @return array<string, list<string>> */
    public function graph(): array
    {
        return $this->edges;
    }

    public function compile(string $namespace, string $class): string
    {
        $ids = array_keys($this->services);
        sort($ids);
        $methodOf = [];
        foreach ($ids as $i => $id) {
            $methodOf[$id] = 's' . $i;
        }

        $lifetimes = [];
        $synthetic = [];
        $arms = [];
        $methods = [];
        foreach ($ids as $id) {
            $definition = $this->services[$id];
            $lifetimes[$id] = $definition->lifetime->code();
            if ($definition->synthetic) {
                $synthetic[$id] = true;
            }
            $arms[] = '            ' . Php::string($id) . ' => $this->' . $methodOf[$id] . '($scope),';
            $methods[] = $this->method($methodOf[$id], $definition);
        }

        $aliases = $this->aliases;
        ksort($aliases);

        return "<?php\n\n// Generated by Keel. Do not edit: run `keel build` instead.\n\ndeclare(strict_types=1);\n\n"
            . "namespace $namespace;\n\n"
            . "use Keel\\Container\\Scope;\n\n"
            . "final class $class extends \\Keel\\Container\\Container\n{\n"
            . '    protected const array LIFETIMES = ' . Php::export($lifetimes, 1) . ";\n\n"
            . '    protected const array ALIASES = ' . Php::export($aliases, 1) . ";\n\n"
            . '    protected const array SYNTHETIC = ' . Php::export($synthetic, 1) . ";\n\n"
            . "    protected function build(string \$id, ?Scope \$scope): object\n    {\n"
            . "        return match (\$id) {\n" . implode("\n", $arms) . "\n"
            . "            default => throw \\Keel\\Container\\Exception\\ServiceNotFound::for(\$id),\n"
            . "        };\n    }\n\n"
            . implode("\n", $methods)
            . "}\n";
    }

    private function method(string $name, ServiceDefinition $definition): string
    {
        $returnType = '\\' . ltrim($definition->id, '\\');
        if ($definition->synthetic) {
            $body = '$this->synthetic(' . Php::string($definition->id) . ');';

            return "    private function $name(?Scope \$scope): never\n    {\n        $body\n    }\n";
        }

        $arguments = [];
        foreach ($definition->arguments as $argument) {
            $arguments[] = $argument->name . ': ' . $this->argumentExpression($argument);
        }
        $argumentList = $arguments === [] ? '' : "\n            " . implode(",\n            ", $arguments) . ",\n        ";

        if ($definition->factory !== null) {
            [$owner, $method] = $definition->factory;
            $body = 'return $this->resolve(\\' . $owner . '::class, $scope)->' . $method . '(' . $argumentList . ');';
        } else {
            $body = 'return new \\' . $definition->class . '(' . $argumentList . ');';
        }

        return "    private function $name(?Scope \$scope): $returnType\n    {\n        $body\n    }\n";
    }

    private function argumentExpression(Argument $argument): string
    {
        switch ($argument->kind) {
            case Argument::SERVICE:
                if ($this->resolvable($argument->type)) {
                    return '$this->resolve(\\' . ltrim($argument->type, '\\') . '::class, $scope)';
                }

                return Php::export($argument->default);
            case Argument::ALL:
                $items = array_map(
                    static fn (string $id): string => '$this->resolve(\\' . $id . '::class, $scope)',
                    $this->implementationsOf($argument->type),
                );

                return '[' . implode(', ', $items) . ']';
            case Argument::CONFIG:
                $method = match ($argument->type) {
                    'string' => 'configString',
                    'int' => 'configInt',
                    'float' => 'configFloat',
                    'bool' => 'configBool',
                    'list<string>' => 'configStringList',
                    default => 'configArray',
                };
                $call = '$this->' . $method . '(' . Php::string((string) $argument->configKey);
                if ($argument->hasDefault && $argument->default !== null) {
                    $call .= ', ' . Php::export($argument->default);
                }

                return $call . ')';
            default:
                return Php::export($argument->default);
        }
    }

    /** @return list<string> */
    private function dependenciesOf(ServiceDefinition $definition): array
    {
        $dependencies = [];
        if ($definition->factory !== null) {
            $dependencies[] = $definition->factory[0];
        }

        foreach ($definition->arguments as $argument) {
            if ($argument->kind === Argument::SERVICE) {
                if ($this->resolvable($argument->type)) {
                    $dependencies[] = $this->target($argument->type);
                } elseif (!$argument->hasDefault && !$argument->nullable) {
                    $this->errors[] = \sprintf(
                        '%s needs %s (parameter $%s), which is not a service. %s',
                        self::short($definition->origin),
                        $argument->type,
                        $argument->name,
                        interface_exists($argument->type)
                            ? 'Bind an implementation in app.php: ->bind(' . self::short($argument->type) . '::class, YourImplementation::class).'
                            : 'Add #[Singleton], #[Scoped] or #[Transient] to ' . self::short($argument->type) . '.',
                    );
                }
            } elseif ($argument->kind === Argument::ALL) {
                foreach ($this->implementationsOf($argument->type) as $id) {
                    $dependencies[] = $id;
                }
            }
        }

        return array_values(array_unique($dependencies));
    }

    private function resolvable(string $type): bool
    {
        return isset($this->services[$this->target($type)]);
    }

    private function target(string $type): string
    {
        return $this->aliases[$type] ?? $type;
    }

    /** @return list<string> */
    private function implementationsOf(string $type): array
    {
        $found = [];
        foreach ($this->services as $id => $definition) {
            if (!$definition->synthetic && is_a($definition->producedType(), $type, true)) {
                $found[] = $id;
            }
        }
        sort($found);

        return $found;
    }

    private function requiresScope(string $id): bool
    {
        if (isset($this->needsScope[$id])) {
            return $this->needsScope[$id];
        }
        $definition = $this->services[$id];
        $result = match ($definition->lifetime) {
            Lifetime::Scoped => true,
            Lifetime::Singleton => false,
            Lifetime::Transient => array_reduce(
                $this->edges[$id] ?? [],
                fn (bool $carry, string $dep): bool => $carry || $this->requiresScope($dep),
                false,
            ),
        };

        return $this->needsScope[$id] = $result;
    }

    private function describeScopePath(string $id): string
    {
        $definition = $this->services[$id];
        if ($definition->lifetime === Lifetime::Scoped) {
            return 'Scoped ' . self::short($id);
        }
        foreach ($this->edges[$id] ?? [] as $dependency) {
            if ($this->requiresScope($dependency)) {
                return 'Transient ' . self::short($id) . ', which depends on ' . $this->describeScopePath($dependency);
            }
        }

        return self::short($id);
    }

    private function detectCycles(): void
    {
        $state = [];
        $stack = [];
        $visit = function (string $id) use (&$visit, &$state, &$stack): void {
            $state[$id] = 1;
            $stack[] = $id;
            foreach ($this->edges[$id] ?? [] as $dependency) {
                if (($state[$dependency] ?? 0) === 1) {
                    $cycle = \array_slice($stack, (int) array_search($dependency, $stack, true));
                    $cycle[] = $dependency;
                    $this->errors[] = 'Circular dependency: ' . implode(' -> ', array_map(self::short(...), $cycle)) . '.';
                } elseif (($state[$dependency] ?? 0) === 0) {
                    $visit($dependency);
                }
            }
            array_pop($stack);
            $state[$id] = 2;
        };

        foreach (array_keys($this->edges) as $id) {
            if (($state[$id] ?? 0) === 0) {
                $visit($id);
            }
        }
    }

    private static function short(string $class): string
    {
        $pos = strrpos($class, '\\');

        return $pos === false ? $class : substr($class, $pos + 1);
    }
}
