<?php

declare(strict_types=1);

namespace Keel\Build\Types;

/**
 * Generates one static method per output class that maps public properties to a
 * JSON-ready array. Enums become their value, dates RFC 3339 strings.
 */
final class SerializerCompiler
{
    /** @var array<class-string, string> */
    private array $methods = [];

    /** @var list<class-string> */
    private array $pending = [];

    public function __construct(private readonly TypeAnalyzer $analyzer)
    {
    }

    /** @param class-string $class */
    public function entry(string $class): string
    {
        $this->require($class);

        return 's_' . HydratorCompiler::id($class);
    }

    public function compile(string $namespace, string $className): string
    {
        while ($this->pending !== []) {
            $class = array_shift($this->pending);
            $this->methods[$class] = $this->method($class);
        }
        ksort($this->methods);

        return "<?php\n\n// Generated by Keel. Do not edit: run `keel build` instead.\n\ndeclare(strict_types=1);\n\n"
            . "namespace $namespace;\n\nfinal class $className\n{\n"
            . implode("\n", $this->methods) . "}\n";
    }

    /** @param class-string $class */
    private function require(string $class): void
    {
        if (!isset($this->methods[$class])) {
            $this->methods[$class] = '';
            $this->pending[] = $class;
        }
    }

    /** @param class-string $class */
    private function method(string $class): string
    {
        $entries = [];
        foreach ($this->analyzer->outputFields($class) as $field) {
            $entries[] = '            ' . var_export($field->name, true) . ' => ' . $this->expression($field->type, '$o->' . $field->name, 0) . ',';
        }
        $body = $entries === [] ? '[]' : "[\n" . implode("\n", $entries) . "\n        ]";

        return '    /** @return array<string, mixed> */' . "\n"
            . '    public static function s_' . HydratorCompiler::id($class) . "(\\$class \$o): array\n    {\n"
            . "        return $body;\n    }\n";
    }

    private function expression(TypeInfo $type, string $value, int $depth): string
    {
        $plain = match ($type->kind) {
            TypeInfo::STRING, TypeInfo::INT, TypeInfo::FLOAT, TypeInfo::BOOL => $value,
            TypeInfo::ENUM => $value . '->value',
            TypeInfo::DATETIME => $value . '->format(\DATE_RFC3339_EXTENDED)',
            TypeInfo::OBJECT => $this->object($type->classOrFail(), $value),
            TypeInfo::LIST => $this->list($type, $value, $depth),
            TypeInfo::VECTOR => $value . '->toArray()',
        };

        if ($type->nullable && $plain !== $value) {
            return "($value === null ? null : $plain)";
        }

        return $plain;
    }

    /** @param class-string $class */
    private function object(string $class, string $value): string
    {
        $this->require($class);

        return 'self::s_' . HydratorCompiler::id($class) . "($value)";
    }

    private function list(TypeInfo $type, string $value, int $depth): string
    {
        $item = $type->item ?? new TypeInfo(TypeInfo::STRING);
        if ($item->isScalar()) {
            return $value;
        }
        $var = '$i' . $depth;

        return "\\array_map(static fn (\$i$depth) => " . $this->expression($item, $var, $depth + 1) . ", $value)";
    }
}
