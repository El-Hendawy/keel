<?php

declare(strict_types=1);

namespace Keel\Build\Types;

use Keel\Build\Php;

/**
 * Generates one static method per input class that turns decoded JSON (or a query
 * string) into a typed object, collecting every violation with its path.
 *
 * Unknown fields are rejected: a client sending `merchantID` instead of `merchantId`
 * gets a 422 that says so, rather than a silently ignored field.
 */
final class HydratorCompiler
{
    /** @var array<class-string, string> class => generated method body */
    private array $methods = [];

    /** @var list<class-string> */
    private array $pending = [];

    private int $var = 0;

    public function __construct(private readonly TypeAnalyzer $analyzer)
    {
    }

    /**
     * @param class-string $class
     * Registers an input class and returns the name of its public entry method.
     */
    public function entry(string $class): string
    {
        $this->require($class);

        return 'h_' . self::id($class);
    }

    public function compile(string $namespace, string $className): string
    {
        while ($this->pending !== []) {
            $class = array_shift($this->pending);
            $this->methods[$class] = $this->objectMethod($class);
        }
        ksort($this->methods);

        $code = "<?php\n\n// Generated by Keel. Do not edit: run `keel build` instead.\n\ndeclare(strict_types=1);\n\n"
            . "namespace $namespace;\n\nuse Keel\\Validation\\Violation;\n\n"
            . "final class $className\n{\n";
        foreach (array_keys($this->methods) as $class) {
            $id = self::id($class);
            $code .= "    public static function h_$id(mixed \$data, bool \$lenient = false): \\$class\n    {\n"
                . "        \$errors = [];\n"
                . "        \$result = self::o_$id(\$data, '', \$errors, \$lenient);\n"
                . "        if (\$result === null || \$errors !== []) {\n"
                . "            throw new \\Keel\\Validation\\ValidationFailed(\$errors);\n        }\n\n"
                . "        return \$result;\n    }\n\n";
        }

        return $code . implode("\n", $this->methods) . "}\n";
    }

    public static function id(string $class): string
    {
        return substr(md5($class), 0, 12) . '_' . str_replace('\\', '_', (string) strrchr('\\' . $class, '\\'));
    }

    /** @param class-string $class */
    private function require(string $class): void
    {
        if (!isset($this->methods[$class]) && !\in_array($class, $this->pending, true)) {
            $this->pending[] = $class;
            $this->methods[$class] = ''; // reserve: prevents infinite recursion on self-references
        }
    }

    /** @param class-string $class */
    private function objectMethod(string $class): string
    {
        $this->var = 0;
        $id = self::id($class);
        $fields = $this->analyzer->inputFields($class);
        $known = [];
        foreach ($fields as $field) {
            $known[$field->name] = true;
        }

        $lines = [];
        $lines[] = "if (!\\is_array(\$in) || (\$in !== [] && \\array_is_list(\$in))) {";
        $lines[] = "    \$errors[] = new Violation(\$path, 'type', 'Must be an object.');";
        $lines[] = '';
        $lines[] = '    return null;';
        $lines[] = '}';
        $lines[] = '$start = \\count($errors);';
        $lines[] = 'foreach ($in as $key => $_) {';
        $lines[] = '    if (!isset(' . Php::export($known) . '[$key])) {';
        $lines[] = "        \$errors[] = new Violation(Violation::at(\$path, (string) \$key), 'unknown_field', 'Unknown field.');";
        $lines[] = '    }';
        $lines[] = '}';

        $args = [];
        foreach ($fields as $i => $field) {
            $out = '$f' . $i;
            $args[] = $field->name . ': ' . $out;
            $key = Php::string($field->name);
            $path = 'Violation::at($path, ' . $key . ')';
            $lines[] = "$out = null;";
            $lines[] = "if (!\\array_key_exists($key, \$in)) {";
            if ($field->hasDefault) {
                $lines[] = "    $out = " . Php::export($field->default) . ';';
            } else {
                $lines[] = "    \$errors[] = new Violation($path, 'required', 'This field is required.');";
            }
            $lines[] = '} else {';
            foreach ($this->value($field->type, "\$in[$key]", $out, $path, $field->constraints) as $line) {
                $lines[] = '    ' . $line;
            }
            $lines[] = '}';
        }

        $required = [];
        foreach ($fields as $i => $field) {
            if (!$field->type->nullable) {
                $required[] = '$f' . $i . ' === null';
            }
        }
        $lines[] = 'if (' . implode(' || ', ['\\count($errors) > $start', ...$required]) . ') {';
        $lines[] = '    return null;';
        $lines[] = '}';
        $lines[] = '';
        // A constructor may enforce rules across fields by throwing ValidationFailed; its
        // violations are reported under this object's path like any other.
        $lines[] = 'try {';
        $lines[] = $args === []
            ? "    return new \\$class();"
            : "    return new \\$class(\n        " . implode(",\n        ", $args) . ",\n    );";
        $lines[] = '} catch (\\Keel\\Validation\\ValidationFailed $e) {';
        $lines[] = '    foreach ($e->violations as $violation) {';
        $lines[] = "        \$errors[] = new Violation(\$violation->path === '' ? \$path : Violation::at(\$path, \$violation->path), \$violation->code, \$violation->message);";
        $lines[] = '    }';
        $lines[] = '';
        $lines[] = '    return null;';
        $lines[] = '}';

        $body = implode("\n", array_map(static fn (string $l): string => $l === '' ? '' : '        ' . $l, explode("\n", implode("\n", $lines))));

        return "    /** @param list<Violation> \$errors */\n"
            . "    private static function o_$id(mixed \$in, string \$path, array &\$errors, bool \$lenient): ?\\$class\n    {\n"
            . $body . "\n    }\n";
    }

    /**
     * @param list<\Keel\Validation\Constraint> $constraints
     * @return list<string>
     */
    private function value(TypeInfo $type, string $in, string $out, string $path, array $constraints): array
    {
        $n = ++$this->var;
        $v = '$v' . $n;
        $ok = '$ok' . $n;
        $lines = ["$v = $in;", "$ok = false;"];
        $lines[] = "if ($v === null) {";
        $lines[] = $type->nullable
            ? "    $out = null;"
            : "    \$errors[] = new Violation($path, 'null', 'Must not be null.');";
        $lines[] = '} else {';

        $inner = match ($type->kind) {
            TypeInfo::STRING => $this->simple("\\is_string($v)", $v, $out, $ok, $path, 'Must be a string.'),
            TypeInfo::BOOL => $this->coerced("\\is_bool($v)", 'bool', $v, $out, $ok, $path, 'Must be a boolean.'),
            TypeInfo::INT => $this->coerced("\\is_int($v)", 'int', $v, $out, $ok, $path, 'Must be an integer.'),
            TypeInfo::FLOAT => [
                "if (\\is_float($v) || \\is_int($v)) {",
                "    $out = (float) $v;",
                "    $ok = true;",
                "} elseif (\$lenient && \\is_string($v) && (\$c = \\Keel\\Validation\\Coerce::float($v)) !== null) {",
                "    $out = \$c;",
                "    $ok = true;",
                '} else {',
                "    \$errors[] = new Violation($path, 'type', 'Must be a number.');",
                '}',
            ],
            TypeInfo::ENUM => $this->enum($type->classOrFail(), $v, $out, $ok, $path),
            TypeInfo::DATETIME => [
                "if (\\is_string($v) && (\$c = \\Keel\\Validation\\Coerce::dateTime($v)) !== null) {",
                "    $out = \$c;",
                "    $ok = true;",
                '} else {',
                "    \$errors[] = new Violation($path, 'type', 'Must be an RFC 3339 date-time.');",
                '}',
            ],
            TypeInfo::OBJECT => $this->object($type->classOrFail(), $v, $out, $ok, $path),
            TypeInfo::LIST => $this->list($type, $v, $out, $ok, $path),
        };
        foreach ($inner as $line) {
            $lines[] = '    ' . $line;
        }

        foreach ($constraints as $constraint) {
            $lines[] = "    if ($ok && !(" . $constraint->compile($out) . ')) {';
            $lines[] = "        \$errors[] = new Violation($path, " . Php::string($constraint->code()) . ', ' . Php::string($constraint->message()) . ');';
            $lines[] = '    }';
        }
        $lines[] = '}';

        return $lines;
    }

    /** @return list<string> */
    private function simple(string $check, string $v, string $out, string $ok, string $path, string $message): array
    {
        return [
            "if ($check) {",
            "    $out = $v;",
            "    $ok = true;",
            '} else {',
            "    \$errors[] = new Violation($path, 'type', " . Php::string($message) . ');',
            '}',
        ];
    }

    /** @return list<string> */
    private function coerced(string $check, string $kind, string $v, string $out, string $ok, string $path, string $message): array
    {
        return [
            "if ($check) {",
            "    $out = $v;",
            "    $ok = true;",
            "} elseif (\$lenient && \\is_string($v) && (\$c = \\Keel\\Validation\\Coerce::$kind($v)) !== null) {",
            "    $out = \$c;",
            "    $ok = true;",
            '} else {',
            "    \$errors[] = new Violation($path, 'type', " . Php::string($message) . ');',
            '}',
        ];
    }

    /** @return list<string> */
    private function enum(string $class, string $v, string $out, string $ok, string $path): array
    {
        $values = array_map(strval(...), TypeInfo::enumValues($class));
        $intBacked = TypeInfo::isIntBacked($class);
        $lookup = $intBacked
            ? "(\\is_int($v) ? \\$class::tryFrom($v) : (\$lenient && \\is_string($v) && (\$i = \\Keel\\Validation\\Coerce::int($v)) !== null ? \\$class::tryFrom(\$i) : null))"
            : "(\\is_string($v) ? \\$class::tryFrom($v) : null)";

        return [
            "if ((\$c = $lookup) !== null) {",
            "    $out = \$c;",
            "    $ok = true;",
            '} else {',
            "    \$errors[] = new Violation($path, 'enum', " . Php::string('Must be one of: ' . implode(', ', $values) . '.') . ');',
            '}',
        ];
    }

    /**
     * @param class-string $class
     * @return list<string>
     */
    private function object(string $class, string $v, string $out, string $ok, string $path): array
    {
        $this->require($class);

        return [
            "$out = self::o_" . self::id($class) . "($v, $path, \$errors, \$lenient);",
            "$ok = $out !== null;",
        ];
    }

    /** @return list<string> */
    private function list(TypeInfo $type, string $v, string $out, string $ok, string $path): array
    {
        $n = $this->var;
        $index = '$i' . $n;
        $item = '$t' . $n;
        $lines = [
            "if (!\\is_array($v) || !\\array_is_list($v)) {",
            "    \$errors[] = new Violation($path, 'type', 'Must be a list.');",
            '} else {',
            "    $out = [];",
            "    $ok = true;",
            "    foreach ($v as $index => \$item$n) {",
            "        $item = null;",
        ];
        $itemPath = "$path . '[' . $index . ']'";
        foreach ($this->value($type->item ?? new TypeInfo(TypeInfo::STRING), "\$item$n", $item, $itemPath, []) as $line) {
            $lines[] = '        ' . $line;
        }
        $lines[] = "        if ($item !== null) {";
        $lines[] = "            {$out}[] = $item;";
        $lines[] = '        } else {';
        $lines[] = "            $ok = false; // an invalid item was reported; skip list-level rules";
        $lines[] = '        }';
        $lines[] = '    }';
        $lines[] = '}';

        return $lines;
    }
}
