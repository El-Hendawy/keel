<?php

declare(strict_types=1);

namespace Keel\Tests\Orm;

use Keel\Build\BuildFailed;
use Keel\Build\Builder;
use Keel\Orm\Dialect\Dialects;
use Keel\Orm\EntityMap;
use Keel\Orm\Schema;
use Keel\Runtime\AppDefinition;
use Keel\Testing\TestApp;
use PHPUnit\Framework\TestCase;

/**
 * SQL generated for engines without a server in this test run (SQL Server, Oracle, ANSI),
 * next to the ones the ORM suite runs against.
 */
final class DialectTest extends TestCase
{
    public function testPagination(): void
    {
        $sql = 'SELECT * FROM t ORDER BY a';
        self::assertSame("$sql LIMIT 10 OFFSET 20", Dialects::for('pgsql')->paginate($sql, 10, 20));
        self::assertSame("$sql LIMIT 10 OFFSET 20", Dialects::for('mysql')->paginate($sql, 10, 20));
        self::assertSame("$sql LIMIT 10", Dialects::for('sqlite')->paginate($sql, 10, null));
        self::assertSame("$sql OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY", Dialects::for('sqlsrv')->paginate($sql, 10, 20));
        self::assertSame('SELECT * FROM t ORDER BY (SELECT NULL) OFFSET 0 ROWS FETCH NEXT 5 ROWS ONLY', Dialects::for('dblib')->paginate('SELECT * FROM t', 5, null));
        self::assertSame("$sql OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY", Dialects::for('oci')->paginate($sql, 10, 20));
        self::assertSame("$sql FETCH FIRST 10 ROWS ONLY", Dialects::for('firebird')->paginate($sql, 10, null));
    }

    public function testQuotingAndUpserts(): void
    {
        self::assertSame('[or]]der]', Dialects::for('sqlsrv')->quote('or]der'));
        self::assertSame('`a``b`', Dialects::for('mysql')->quote('a`b'));
        self::assertSame('"a""b"', Dialects::for('oci')->quote('a"b'));

        self::assertSame(
            'INSERT INTO "t" ("id", "n") VALUES (?, ?), (?, ?) ON CONFLICT ("id") DO UPDATE SET "n" = excluded."n"',
            Dialects::for('pgsql')->upsert('t', ['id', 'n'], 2, ['id'], ['n']),
        );
        self::assertSame(
            'INSERT INTO `t` (`id`, `n`) VALUES (?, ?) ON DUPLICATE KEY UPDATE `n` = VALUES(`n`)',
            Dialects::for('mysql')->upsert('t', ['id', 'n'], 1, ['id'], ['n']),
        );
        self::assertSame(
            'MERGE INTO [t] t USING (SELECT ? AS [id], ? AS [n]) s ON (t.[id] = s.[id]) WHEN MATCHED THEN UPDATE SET [n] = s.[n] WHEN NOT MATCHED THEN INSERT ([id], [n]) VALUES (s.[id], s.[n]);',
            Dialects::for('sqlsrv')->upsert('t', ['id', 'n'], 1, ['id'], ['n']),
        );
        self::assertStringContainsString('USING (SELECT ? AS "id", ? AS "n" FROM dual)', Dialects::for('oci')->upsert('t', ['id', 'n'], 1, ['id'], ['n']));
    }

    public function testSchemaForEveryEngine(): void
    {
        $app = TestApp::boot(__DIR__ . '/../Fixtures/OrmBlog/app.php', ['database' => ['dsn' => 'sqlite::memory:']]);
        $map = $app->container()->get(EntityMap::class);
        $ddl = static fn (string $driver): string => implode(";\n", (new Schema($map, Dialects::for($driver)))->create());

        self::assertStringContainsString('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $ddl('pgsql'));
        self::assertStringContainsString('"meta" JSONB NOT NULL', $ddl('pgsql'));
        self::assertStringContainsString('`id` BIGINT AUTO_INCREMENT PRIMARY KEY', $ddl('mysql'));
        self::assertStringContainsString('`created_at` DATETIME(6) NULL', $ddl('mysql'));
        self::assertStringContainsString('[id] BIGINT IDENTITY(1,1) PRIMARY KEY', $ddl('sqlsrv'));
        self::assertStringContainsString('[featured] BIT NOT NULL', $ddl('sqlsrv'));
        self::assertStringContainsString('[title] NVARCHAR(255) NOT NULL', $ddl('sqlsrv'));
        self::assertStringContainsString('"price" NUMBER(10, 2) NOT NULL', $ddl('oci'));
        self::assertStringContainsString('"title" VARCHAR2(255 CHAR) NOT NULL', $ddl('oci'));
        self::assertStringContainsString('"id" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $ddl('oci'));
        self::assertStringContainsString('"price" DECIMAL(10, 2) NOT NULL', $ddl('ibm'));
        self::assertStringContainsString('CREATE TABLE "post_tags"', $ddl('ibm'));
    }

    public function testMappingMistakesAreBuildErrors(): void
    {
        $app = AppDefinition::create(__DIR__ . '/../Fixtures/OrmBroken', 'orm-broken')
            ->scan('.')
            ->buildDir(sys_get_temp_dir() . '/keel-tests/orm-broken');
        try {
            (new Builder($app, 'test'))->build();
            self::fail('The build should fail.');
        } catch (BuildFailed $e) {
            $message = $e->getMessage();
            self::assertStringContainsString('has #[Entity] classes. Add ->withDatabase()', $message);
            self::assertStringContainsString('Entity Keel\Tests\Fixtures\OrmBroken\Broken has no #[Id] property.', $message);
            self::assertStringContainsString('$lines is a hasMany relation: declare it as `public Many $lines = new Many()`', $message);
            self::assertStringContainsString('$tags targets stdClass, which is not an #[Entity]', $message);
            self::assertStringContainsString('$stamp: #[Version] must be a non-readonly int', $message);
            self::assertStringContainsString('$when: DateTime cannot be a column', $message);
        }
    }
}
